import { Component, type ReactNode } from 'react';
/** An optional lazy visual module must never take the saved learning engine down. */
export class LearningModuleBoundary extends Component<
  { children: ReactNode; fallback: ReactNode },
  { failed: boolean }
> {
  state = { failed: false };
  static getDerivedStateFromError() {
    return { failed: true };
  }
  render() {
    return this.state.failed ? this.props.fallback : this.props.children;
  }
}
